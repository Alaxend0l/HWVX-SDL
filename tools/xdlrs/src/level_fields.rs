//! src/game/Port_LevelFields.inc from the schemas: for each struct, the words a shared level's
//! patches must never set (Port_Level.c): its pointers (every field with an `x-link`: object
//! links, texture ids, handle arrays), and the counts those links name; with the struct a
//! link leads to, so the port can walk the base world's records from the World and know the
//! type of every word it reaches.
//!
//! ```text
//! xdlrs level gen-fields            write it
//! xdlrs level gen-fields --check    1 if the file isn't what the schemas give
//! ```

use crate::error::{Error, Result};
use crate::schema::{self, Schemas};
use serde_json::Value;
use std::collections::BTreeMap;
use std::path::Path;

pub const OUT: &str = "src/game/Port_LevelFields.inc";

/// The struct a link's `target` names, if it has a schema ("struct TilePath" -> "TilePath").
fn target<'a>(s: &Schemas, link: &'a Value) -> Option<&'a str> {
    let t = link.get("target")?.as_str()?;
    let t = t.strip_prefix("struct ").unwrap_or(t);
    s.top(t).map(|_| t)
}

struct Entry {
    off: u32,
    size: u32,
    kind: &'static str,
    target: Option<String>,
    count: Option<u32>,
    item: u32,
}

/// The pointer and count words of struct `sch` at `base` (nested structs flattened).
fn entries(s: &Schemas, sch: &Value, base: u32, out: &mut Vec<Entry>, depth: usize) -> Result<()> {
    if depth > 8 {
        return Err(Error::xdl("nested structs too deep"));
    }
    let fields = schema::fields(sch);
    let mut counts: BTreeMap<String, ()> = BTreeMap::new();
    for (_, p) in &fields {
        let link = p.get("x-link").or_else(|| p.get("items").and_then(|i| i.get("x-link")));
        if let Some(c) = link.and_then(|l| l.get("count")).and_then(Value::as_str) {
            counts.insert(c.to_string(), ());
        }
    }
    for (k, p) in &fields {
        let off = base + schema::offset(p)?;
        let ct = schema::ctype(p);
        let size = s.size_of(ct).unwrap_or(4) as u32;
        let link = p.get("x-link").or_else(|| p.get("items").and_then(|i| i.get("x-link")));
        if counts.contains_key(k.as_str()) {
            out.push(Entry { off, size, kind: "LF_COUNT", target: None, count: None, item: 0 });
        } else if let Some(l) = link {
            let (_, dims) = schema::parse_ctype(ct);
            let follow = l.get("kind").and_then(Value::as_str) == Some("object") && dims.is_empty();
            let t = if follow { target(s, l).map(str::to_string) } else { None };
            let count = l.get("count").and_then(Value::as_str).and_then(|c| {
                fields.iter().find(|(n, _)| n.as_str() == c).and_then(|(_, q)| schema::offset(q).ok()).map(|o| base + o)
            });
            let item = match (&t, l.get("item-size").and_then(Value::as_u64)) {
                (_, Some(n)) => n as u32,
                (Some(t), None) => schema::size(s.top(t).unwrap())? as u32,
                _ => 0,
            };
            out.push(Entry { off, size, kind: "LF_PTR", target: t, count, item });
        } else if ct.starts_with("PTR32(") || ct.starts_with("FPTR32") {
            out.push(Entry { off, size, kind: "LF_PTR", target: None, count: None, item: 0 });
        } else if let Some(sub) = s.ref_(p) {
            entries(s, sub, off, out, depth + 1)?;
        }
    }
    Ok(())
}

/// The file's text.
pub fn text(s: &Schemas) -> Result<String> {
    let names: Vec<String> = s.top.iter().map(|(t, _, _)| t.clone()).filter(|t| s.top(t).is_some_and(|x| x.get("x-size").is_some())).collect();
    let mut sorted = names.clone();
    sorted.sort();
    let mut o = String::from(
        "/* Generated by `xdlrs level gen-fields` (tools/xdlrs/src/level_fields.rs) from the schemas: do not\n \
         * edit. A struct's pointer words (x-link fields) and the counts they name: a shared level's patches\n \
         * never set them (Port_Level.c). */\n\n",
    );
    for n in &sorted {
        let sch = s.top(n).unwrap();
        let mut es = vec![];
        entries(s, sch, 0, &mut es, 0)?;
        o.push_str(&format!("static const LevelField s_lf_{n}[] = {{\n"));
        for e in &es {
            let t = e.target.as_ref().and_then(|t| sorted.iter().position(|x| x == t)).map(|i| i as i32).unwrap_or(-1);
            o.push_str(&format!(
                "    {{ 0x{:X}, {}, {}, {}, 0x{:X}, {} }},\n",
                e.off,
                e.size,
                e.kind,
                t,
                e.count.map(|c| c + 1).unwrap_or(0),
                e.item
            ));
        }
        if es.is_empty() {
            o.push_str("    { 0, 0, LF_NONE, -1, 0, 0 },\n");
        }
        o.push_str("};\n");
    }
    o.push_str("\nstatic const LevelStruct s_levelStructs[] = {\n");
    for n in &sorted {
        let sch = s.top(n).unwrap();
        o.push_str(&format!("    {{ \"{n}\", 0x{:X}, s_lf_{n}, SDL_arraysize(s_lf_{n}) }},\n", schema::size(sch)?));
    }
    o.push_str("};\n");
    Ok(o)
}

/// Writes (or with `check`, compares) the file under `root`; the exit code.
pub fn generate(root: &Path, check: bool) -> Result<i32> {
    let s = Schemas::load(&root.join("schemas"))?;
    let t = text(&s)?;
    let p = root.join(OUT);
    if check {
        let ok = std::fs::read_to_string(&p).map(|x| x == t).unwrap_or(false);
        println!("{OUT}: {}", if ok { "up to date" } else { "NOT what the schemas give: run xdlrs level gen-fields" });
        return Ok(if ok { 0 } else { 1 });
    }
    std::fs::write(&p, &t).map_err(|e| Error::io(format!("{}: {e}", p.display())))?;
    println!("{}: {} words", p.display(), t.matches("LF_PTR").count() + t.matches("LF_COUNT").count());
    Ok(0)
}
