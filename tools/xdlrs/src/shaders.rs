//! `xdlrs shaders gen`: src/port/gx_shaders.h from src/port/shaders/ (was tools/gen_shaders.py).
//!
//! The header holds every shader in every form a renderer needs, so building the
//! game needs no shader tools:
//!
//! - GLSL source for OpenGL (gx.vert/gx.frag, includes inlined, no #version);
//! - SPIR-V (Vulkan), MSL (Metal) and DXIL (D3D12) for SDL_GPU, made with
//!   glslang -> spirv-cross -> dxc;
//! - for SDL_GPU, also a pixel shader specialised to each TEV setup in
//!   tools/tevkeys.txt (src/port/gx_tevgen.h; the OpenGL backend makes its own
//!   at run time). Setups not in the list use gx.frag. To add the ones a part of
//!   the game uses, play it with HWVX_TEVKEYS=tools/tevkeys.txt and rerun this.
//!   The GLSL comes from gx_tevgen.c through tools/tevgen_glsl.c, built here
//!   with cc and SDL3 (pkg-config).
//!
//! Unchanged shaders keep their committed code: when a shader's SPIR-V comes out
//! byte for byte as the header has it under the same name, its SPIR-V, MSL and
//! DXIL entries are copied from the header as they are. glslang's SPIR-V only
//! changes with the source (or glslang), while DXIL also changes with the dxc
//! build, so without this every regeneration on another machine rewrote every
//! DXIL blob. `--fresh` writes everything from the tools' output.
//!
//! Tools are looked up in DIR/bin and DIR/dxc/bin (`--tools DIR`, default
//! ~/.local/opt/shadertools), then on PATH. dxc needs its libdxil next to it
//! (lib/) to sign the DXIL where it doesn't sign by itself; unsigned DXIL is
//! rejected by D3D12.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::process::Command;

// gx_gl.c FragDecl: specialised shaders reuse gx.frag up to here
const DECL_END: &str = "\nvec4 tex(int map";
const FIRST_LINE: &str = "/* Generated by xdlrs shaders gen (tools/xdlrs/src/shaders.rs) from src/port/shaders/; do not edit. */\n";

/// (file, stage, also emitted as GLSL for OpenGL)
const SHADERS: [(&str, &str, bool); 4] = [
    ("gx.vert", "vert", true),
    ("gx.frag", "frag", true),
    ("present.vert", "vert", false),
    ("present.frag", "frag", false),
];

type R<T> = std::result::Result<T, String>;

pub struct Opts {
    pub root: PathBuf,
    pub tools: Option<PathBuf>,
    pub fresh: bool,
}

struct Tools {
    glslang: PathBuf,
    spirv_cross: PathBuf,
    dxc: PathBuf,
    dxc_lib: PathBuf,
}

fn find_tool(name: &str, extra: &[PathBuf]) -> R<PathBuf> {
    for d in extra {
        let p = d.join(name);
        if is_exe(&p) {
            return Ok(p);
        }
    }
    if let Some(path) = std::env::var_os("PATH") {
        for d in std::env::split_paths(&path) {
            let p = d.join(name);
            if is_exe(&p) {
                return Ok(p);
            }
        }
    }
    Err(format!("{name} not found (see --tools)"))
}

fn is_exe(p: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    p.metadata().map(|m| m.is_file() && m.permissions().mode() & 0o111 != 0).unwrap_or(false)
}

fn read(p: &Path) -> R<String> {
    std::fs::read_to_string(p).map_err(|e| format!("{}: {e}", p.display()))
}

fn read_bytes(p: &Path) -> R<Vec<u8>> {
    std::fs::read(p).map_err(|e| format!("{}: {e}", p.display()))
}

fn write(p: &Path, d: &[u8]) -> R<()> {
    std::fs::write(p, d).map_err(|e| format!("{}: {e}", p.display()))
}

fn inline_includes(path: &Path) -> R<String> {
    let mut out = String::new();
    for line in read(path)?.split_inclusive('\n') {
        let t = line.trim_start();
        let inc = t.strip_prefix("#include").and_then(|r| {
            let r = r.trim_start();
            let r = r.strip_prefix('"')?;
            Some(&r[..r.find('"')?])
        });
        match inc {
            Some(f) => out += &inline_includes(&path.parent().unwrap_or(Path::new(".")).join(f))?,
            None => out += line,
        }
    }
    Ok(out)
}

fn run(cmd: &mut Command) -> R<()> {
    let o = cmd.output().map_err(|e| format!("{:?}: {e}", cmd.get_program()))?;
    if !o.status.success() {
        let args: Vec<String> = std::iter::once(cmd.get_program())
            .chain(cmd.get_args())
            .map(|a| a.to_string_lossy().into_owned())
            .collect();
        return Err(format!(
            "{} failed:\n{}{}",
            args.join(" "),
            String::from_utf8_lossy(&o.stdout),
            String::from_utf8_lossy(&o.stderr)
        ));
    }
    Ok(())
}

fn c_name(file: &str, kind: &str) -> String {
    format!("{}_{kind}", file.replace('.', "_"))
}

fn c_bytes(name: &str, data: &[u8]) -> String {
    let mut s = format!("static const unsigned char {name}[{}] = {{", data.len());
    for row in data.chunks(16) {
        let hex: Vec<String> = row.iter().map(|b| format!("0x{b:02X}")).collect();
        s += &format!("\n    {},", hex.join(", "));
    }
    s + "\n};"
}

fn c_string(name: &str, text: &str) -> String {
    let mut s = format!("static const char {name}[] =");
    for line in text.lines() {
        s += &format!("\n    \"{}\\n\"", line.replace('\\', "\\\\").replace('"', "\\\""));
    }
    s + ";"
}

/// One shader's SDL_GPU entries: (SPIR-V, MSL, DXIL) as header text.
struct Compiled {
    spv: String,
    msl: String,
    dxil: String,
}

struct Gen<'a> {
    tools: Tools,
    tmp: PathBuf,
    old: HashMap<String, String>,
    fresh: bool,
    kept: Vec<String>,
    written: Vec<String>,
    _o: &'a Opts,
}

impl Gen<'_> {
    /// SPIR-V, MSL and DXIL for one shader (GLSL without #version), named
    /// `base`_spv/_msl/_dxil; the header's entries when its SPIR-V is unchanged.
    fn compile(&mut self, file: &str, base: &str, stage: &str, src: &str) -> R<Compiled> {
        let vk = self.tmp.join(file);
        write(&vk, format!("#version 450\n{src}").as_bytes())?;
        let spv = self.tmp.join(format!("{file}.spv"));
        run(Command::new(&self.tools.glslang).args(["-V", "-S", stage, "-o"]).arg(&spv).arg(&vk))?;
        let spv_text = c_bytes(&format!("{base}_spv"), &read_bytes(&spv)?);
        let names = [format!("{base}_spv"), format!("{base}_msl"), format!("{base}_dxil")];
        if !self.fresh && self.old.get(&names[0]) == Some(&spv_text) {
            if let (Some(m), Some(d)) = (self.old.get(&names[1]), self.old.get(&names[2])) {
                self.kept.push(base.to_string());
                return Ok(Compiled { spv: spv_text, msl: m.clone(), dxil: d.clone() });
            }
        }
        self.written.push(base.to_string());
        let msl = self.tmp.join(format!("{file}.msl"));
        let hlsl = self.tmp.join(format!("{file}.hlsl"));
        // --msl-decoration-binding: SPIR-V bindings become the MSL indices
        // SDL expects ([[texture(n)]]/[[sampler(n)]], [[buffer(0)]])
        run(Command::new(&self.tools.spirv_cross)
            .arg(&spv)
            .args(["--msl", "--msl-version", "20100", "--msl-decoration-binding", "--output"])
            .arg(&msl))?;
        run(Command::new(&self.tools.spirv_cross)
            .arg(&spv)
            .args(["--hlsl", "--shader-model", "60", "--hlsl-enable-compat", "--output"])
            .arg(&hlsl))?;
        let dxil = self.tmp.join(format!("{file}.dxil"));
        let mut lib = self.tools.dxc_lib.clone().into_os_string();
        if let Some(old) = std::env::var_os("LD_LIBRARY_PATH").filter(|v| !v.is_empty()) {
            lib.push(":");
            lib.push(old);
        }
        run(Command::new(&self.tools.dxc)
            .env("LD_LIBRARY_PATH", lib)
            .args(["-T", &format!("{}_6_0", if stage == "vert" { "vs" } else { "ps" }), "-E", "main", "-Fo"])
            .arg(&dxil)
            .arg(&hlsl))?;
        let msl_src = read(&msl)?.replace("\r\n", "\n");
        Ok(Compiled {
            spv: spv_text,
            msl: c_string(&names[1], &msl_src),
            dxil: c_bytes(&names[2], &read_bytes(&dxil)?),
        })
    }

    /// gx_tev_variants[]: SDL_GPU's specialised pixel shaders (gx_sdlgpu.c).
    fn tev_variants(&mut self, frag_src: &str) -> R<String> {
        let root = self._o.root.clone();
        let end = frag_src
            .find(DECL_END)
            .ok_or_else(|| format!("gx.frag has no {:?} (see gx_gl.c FragDecl)", DECL_END.trim()))?;
        let decl = self.tmp.join("decl.glsl");
        write(&decl, frag_src[..end + 1].as_bytes())?;
        let tool = self.tmp.join("tevgen_glsl");
        let flags = Command::new("pkg-config")
            .args(["--cflags", "--libs", "sdl3"])
            .output()
            .ok()
            .filter(|o| o.status.success())
            .ok_or("pkg-config can't find sdl3 (needed for tools/tevgen_glsl.c)")?;
        let port = root.join("src/port");
        let cc = std::env::var("CC").unwrap_or_else(|_| "cc".into());
        run(Command::new(cc)
            .args(["-std=gnu11", "-O1"])
            .arg(format!("-I{}", port.display()))
            .arg(format!("-I{}", root.join("src/game/include").display()))
            .arg(root.join("tools/tevgen_glsl.c"))
            .arg(port.join("gx_tevgen.c"))
            .args(String::from_utf8_lossy(&flags.stdout).split_whitespace())
            .arg("-o")
            .arg(&tool))?;
        let out = self.tmp.join("tev");
        std::fs::create_dir(&out).map_err(|e| format!("{}: {e}", out.display()))?;
        let keys_path = root.join("tools/tevkeys.txt");
        let keys = if keys_path.exists() { keys_path.clone() } else { PathBuf::from("/dev/null") };
        run(Command::new(&tool).arg(&keys).arg(&decl).arg(&out))?;
        let keylines: Vec<Vec<String>> = read(&out.join("keys"))?
            .lines()
            .filter(|l| !l.trim().is_empty())
            .map(|l| l.split_whitespace().map(String::from).collect())
            .collect();
        let mut parts = vec![];
        let mut rows = vec![];
        for (i, k) in keylines.iter().enumerate() {
            let src = read(&out.join(format!("tev{i}.frag")))?;
            let c = self.compile(&format!("tev{i}.frag"), &format!("gx_tev{i}"), "frag", &src)?;
            parts.extend([c.spv, c.msl, c.dxil]);
            let stages: Vec<String> = k[1..].iter().map(|x| format!("0x{x}ull")).collect();
            rows.push(format!(
                "    {{ 0x{}u, {{ {} }},\n      gx_tev{i}_spv, sizeof(gx_tev{i}_spv), gx_tev{i}_msl, gx_tev{i}_dxil, sizeof(gx_tev{i}_dxil) }},",
                k[0],
                stages.join(", ")
            ));
        }
        let shown = keys.strip_prefix(&root).unwrap_or(&keys).display().to_string();
        println!("{} specialised pixel shaders from {shown}", keylines.len());
        let mut table = vec![
            "/* Specialised pixel shaders: GXTevKey misc and stages (gx_tevgen.h), then the code. */".to_string(),
            "typedef struct GXTevVariant {".into(),
            "    unsigned int misc;".into(),
            "    unsigned long long stage[16];".into(),
            "    const unsigned char *spv;".into(),
            "    unsigned int spvSize;".into(),
            "    const char *msl;".into(),
            "    const unsigned char *dxil;".into(),
            "    unsigned int dxilSize;".into(),
            "} GXTevVariant;".into(),
            String::new(),
            format!("#define GX_NUM_TEV_VARIANTS {}", keylines.len()),
        ];
        if !keylines.is_empty() {
            table.push(format!("static const GXTevVariant gx_tev_variants[{}] = {{", keylines.len()));
            table.extend(rows);
            table.push("};".into());
        }
        parts.push(table.join("\n"));
        Ok(parts.join("\n\n"))
    }
}

/// The header's entries by C name (the blocks between blank lines).
fn old_entries(text: &str) -> HashMap<String, String> {
    let mut m = HashMap::new();
    for block in text.split("\n\n") {
        for pre in ["static const unsigned char ", "static const char "] {
            if let Some(rest) = block.strip_prefix(pre)
                && let Some(n) = rest.find('[')
            {
                m.insert(rest[..n].to_string(), block.to_string());
            }
        }
    }
    m
}

pub fn generate(o: &Opts) -> R<()> {
    let home = std::env::var_os("HOME").map(PathBuf::from).unwrap_or_default();
    let prefix = o.tools.clone().unwrap_or_else(|| home.join(".local/opt/shadertools"));
    let extra = [prefix.join("bin"), prefix.join("dxc/bin")];
    let dxc = find_tool("dxc", &extra)?;
    let tools = Tools {
        glslang: find_tool("glslang", &extra)?,
        spirv_cross: find_tool("spirv-cross", &extra)?,
        dxc_lib: dxc.parent().and_then(Path::parent).unwrap_or(Path::new("")).join("lib"),
        dxc,
    };
    let out_path = o.root.join("src/port/gx_shaders.h");
    let old = if o.fresh { HashMap::new() } else { std::fs::read_to_string(&out_path).map(|t| old_entries(&t)).unwrap_or_default() };
    let tmp = std::env::temp_dir().join(format!("xdlrs-shaders-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).map_err(|e| format!("{}: {e}", tmp.display()))?;
    let mut g = Gen { tools, tmp: tmp.clone(), old, fresh: o.fresh, kept: vec![], written: vec![], _o: o };
    let r = (|| -> R<Vec<String>> {
        let mut parts = vec![];
        let mut frag_src = String::new();
        for (file, stage, gl) in SHADERS {
            let src = inline_includes(&o.root.join("src/port/shaders").join(file))?;
            if file == "gx.frag" {
                frag_src = src.clone();
            }
            if gl {
                parts.push(c_string(&c_name(file, "glsl"), &src));
            }
            let base = file.replace('.', "_");
            let c = g.compile(file, &base, stage, &src)?;
            parts.extend([c.spv, c.msl, c.dxil]);
        }
        parts.push(g.tev_variants(&frag_src)?);
        Ok(parts)
    })();
    let _ = std::fs::remove_dir_all(&tmp);
    let parts = r?;
    let text = format!("{FIRST_LINE}#ifndef GX_SHADERS_H\n#define GX_SHADERS_H\n\n{}\n\n#endif\n", parts.join("\n\n"));
    write(&out_path, text.as_bytes())?;
    if !g.kept.is_empty() {
        println!("kept (SPIR-V unchanged): {}", g.kept.join(" "));
    }
    if !g.written.is_empty() {
        println!("compiled: {}", g.written.join(" "));
    }
    println!("wrote src/port/gx_shaders.h");
    Ok(())
}
