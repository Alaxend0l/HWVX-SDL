#!/usr/bin/env python3
"""src/game/Port_ModFields.inc from schemas/*.schema.json: the fields a mod's patch may set
(name, offset, type) and the links its object paths follow, for src/game/Port_Mods.c.

    python3 tools/gen_mod_fields.py            write it
    python3 tools/gen_mod_fields.py --check    1 if the file isn't what the schemas give

tools/xdl_mod.py reads the same schemas (Schemas.fields), so the packer and the port agree on
what is patchable. Run after tools/gen_schemas.py changes a schema.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import xdl_mod as M  # noqa: E402

OUT = M.ROOT / "src" / "game" / "Port_ModFields.inc"
TYPES = {"u8": "MF_U8", "s8": "MF_S8", "char": "MF_S8", "u16": "MF_U16", "s16": "MF_S16", "u32": "MF_U32",
         "s32": "MF_S32", "BOOL": "MF_S32", "int": "MF_S32", "f32": "MF_F32"}


def text():
    s = M.Schemas()
    names = sorted(s.s)
    out = ["/* Generated by tools/gen_mod_fields.py from the schemas (schemas/NAME.schema.json): do not edit. */", ""]
    for n in names:
        out.append(f"static const ModField s_fields_{n}[] = {{")
        fields = s.fields(n)
        for f, (off, prim, count, target) in sorted(fields.items(), key=lambda kv: kv[1][0]):
            if target is not None:
                # count: 1 + the offset of the u32 counting the objects it points to (0: one)
                c = s.count_of(n, f)
                cnt = f"0x{fields[c][0] + 1:X}" if c is not None and s.s[n]["properties"][c]["x-c-type"] in (
                    "u32", "s32") else "0"
                out.append(f'    {{ "{f}", 0x{off:X}, MF_LINK, {cnt}, {names.index(target)} }},')
            elif prim in TYPES:
                out.append(f'    {{ "{f}", 0x{off:X}, {TYPES[prim]}, {count}, -1 }},')
            else:
                out.append(f'    {{ "{f}", 0x{off:X}, MF_OTHER, 0, -1 }},')
        out.append("};")
    out.append("")
    out.append("static const ModStruct s_structs[] = {")
    for n in names:
        out.append(f'    {{ "{n}", {s.s[n]["x-size"]}, s_fields_{n}, SDL_arraysize(s_fields_{n}) }},')
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    t = text()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == t
        print(f"{OUT.name}: {'up to date' if ok else 'NOT what the schemas give: run tools/gen_mod_fields.py'}")
        return 0 if ok else 1
    OUT.write_text(t)
    print(f"{OUT}: {t.count('MF_') } fields")
    return 0


if __name__ == "__main__":
    sys.exit(main())
