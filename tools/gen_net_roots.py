#!/usr/bin/env python3
"""Writes src/port/net_roots.h: the public root certificates the online client trusts
for wss://, for systems with no certificate file to read (Windows). Cloudflare's tunnels
currently chain to Google Trust Services; the others are what it and named tunnels may
move to. Run again when one nears its expiry:

  tools/gen_net_roots.py gtsr1.pem gtsr2.pem ... > src/port/net_roots.h

Fetched from their authorities: pki.goog/repo/certs, letsencrypt.org/certs,
cacerts.digicert.com. Check the fingerprints against theirs before committing."""
import subprocess
import sys

print("/* Generated by tools/gen_net_roots.py: public root certificates, PEM. */")
print("#ifndef NET_ROOTS_H\n#define NET_ROOTS_H\n")
print("static const char g_netRootCertificates[] =")
for path in sys.argv[1:]:
    out = subprocess.run(["openssl", "x509", "-in", path, "-noout", "-subject", "-enddate", "-fingerprint", "-sha256"],
                         capture_output=True, text=True, check=True).stdout.strip().split("\n")
    print("    /* " + "; ".join(out).replace("*/", "") + " */")
    for line in open(path):
        line = line.strip()
        if line:
            print('    "%s\\n"' % line)
print("    ;\n\n#endif")
