#!/usr/bin/env python3
"""tools/gen_mix_pairs.py PAIRING_DIR > src/game/Port_MixPairs.c

The cross-release pairs a mixed build substitutes along (src/game/Port_Mix.c),
from the pairing table of HWVX-X-FILE-EDITOR (docs/xdl-format/pairing/, its
pairing.md has the grammar): per pack, each texture's and sound's index in
the GameCube, PC and PS2 releases' own tables, and the PS2 prototype's
(proto, the fourth column: Port_Proto.c's mode "replace"). Only records two
or more releases share, one of them retail; ids and indices, no game data."""
import glob, json, os, re, sys

TYPES = ["car", "interface", "item", "link", "world", "collision", "world_texture", "geometry", "share",
         "audio", "music"]
RELS = ["gc", "pc", "ps2", "proto"]
KINDS = ["texture", "sound"]


def main(root):
    packs = {}  # (archive, type, id) -> {kind: [(gc, pc, ps2)]}
    for path in sorted(glob.glob(os.path.join(root, "*.jsonl")), key=lambda p: os.path.basename(p).lower()):
        for line in open(path):
            r = json.loads(line)
            if "id" not in r:
                continue
            m = re.match(r"base://([^/]+)/([a-z_]+)_(\d+)/(texture|sound)/", r["id"])
            if not m:
                continue
            rels = [x for x in RELS if x in r]
            if len(rels) < 2 or rels == ["proto"]:
                continue
            key = (m.group(1), TYPES.index(m.group(2)), int(m.group(3)))
            packs.setdefault(key, {k: [] for k in KINDS})[m.group(4)].append(
                tuple(r[x]["i"] if x in r else 0xFFFF for x in RELS))
    out = ["/* Generated by tools/gen_mix_pairs.py from docs/xdl-format/pairing/ (HWVX-X-FILE-EDITOR):",
           " * the textures and sounds two or more releases share, as each release's index in the",
           " * pack's own table: GameCube, PC, PS2, the PS2 prototype (0xFFFF: not in that release).",
           " * Port_Mix.c reads it. */",
           '#include "Port_Mix.h"', "", "const u16 g_portMixPairs[][PORT_MIX_RELS] = {"]
    rows, n = [], 0
    cells = []
    for key in sorted(packs, key=lambda k: (k[0].lower(), k[1], k[2])):
        p = packs[key]
        t, s = sorted(p["texture"]), sorted(p["sound"])
        rows.append('    { "%s", %d, %d, %d, %d, %d },' % (key[0], key[1], key[2], n, len(t), len(s)))
        for rec in t + s:
            cells.append("{%d,%d,%d,%d}" % rec)
        n += len(t) + len(s)
    for i in range(0, len(cells), 8):
        out.append("    " + ",".join(cells[i:i + 8]) + ",")
    out += ["};", "", "/* archive, pack type and id, first pair, textures, then sounds */",
            "const PortMixPairPack g_portMixPairPacks[] = {"] + rows + ["};", "",
            "const u32 g_portMixNumPairPacks = sizeof(g_portMixPairPacks) / sizeof(g_portMixPairPacks[0]);", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
